// ============================================================
// 设计讨论层 —— 角色定义
//
// 与 autowrite/prompts.ts 里的「流水线角色」（规划官 / 写作官 / 校对官 / 评审官）不同：
// 这里的角色负责**内容设计**，靠**互相回应**产出「本章结论」，
// 写作官随后只读结论写正文，不参与争论。
//
// 设计要点：
//   · 讨论必须是来回的 —— 不是各自交一份报告。每个角色都能看到前面人的发言。
//   · 输出是「给同伴看的话」，不是 JSON、不是小标题 —— 那才叫交流。
//   · 设定管家是**唯一必须查库**的角色：它拦的每一条都要有出处，不能凭印象。
//   · 定稿官把讨论收敛成可比对的清单 —— 意图复核就靠对照它。
// ============================================================

