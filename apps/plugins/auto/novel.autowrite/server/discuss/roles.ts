/**
 * 写作官篇幅契约。
 *
 * 提示词与运行时的字数自检**共用这两个常量** —— 两处各写一个数字必然漂移
 * （2026-09-12 实测：提示词写「2500–4000」，三次产出 2115/2145/2179，全部低于下限）。
 * 改成单一目标值而非区间：给区间时模型倾向于朝下限写。
 */
export const WRITER_TARGET_CHARS = 3000;
export const WRITER_MIN_CHARS = 2500;
/**
 * 篇幅上限。
 *
 * ★ 2026-10-16 加（实测教训）：长跑 13 章里**没有一章**落在 2500–3000 目标带，
 *   均值 4646、最长 7561，且**越写越长**。给下限而不给上限，模型会把"不得少于"
 *   读成"越多越好"，最后靠**成段重复**把字数堆上去（第 1 章 164 段里 59 段重复）。
 *   上限的作用不是省 token，是**堵掉"用重复凑篇幅"这条路**。
 */
